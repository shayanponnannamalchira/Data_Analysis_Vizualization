"""
U3&U4 Interview Q3. Mean vs Median
A company's employee salary data has a mean of Rs 85,000 and a median of Rs 45,000.
What does this difference suggest about the data? Which measure would you use to
represent a typical employee salary and why?
"""
print(f"Mean salary  : Rs 85,000")
print(f"Median salary: Rs 45,000")

print("""
Answer: A mean far higher than the median indicates the salary distribution is
right-skewed - a small number of very high earners (executives) are pulling the mean
upward, while most employees earn much closer to the median. The median is the better
measure of a "typical" employee's salary here because it isn't distorted by these
high-end outliers.
""")
