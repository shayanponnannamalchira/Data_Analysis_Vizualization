"""
U3&U4 Interview Q6. EDA Interpretation
A scatter plot shows points generally moving upward from left to right, but the
points are widely scattered. Would you describe the relationship as positive and
strong or positive and weak? Explain.
"""
print("""
Answer: Positive and weak. The upward trend indicates a positive relationship
(direction), but the wide scatter around that trend means the points don't follow the
line closely, which corresponds to a low-to-moderate correlation coefficient. Strength
of a relationship is about how tightly points cluster around the trend, not just the
trend's direction - so "widely scattered" directly implies a weak relationship despite
the positive direction.
""")
