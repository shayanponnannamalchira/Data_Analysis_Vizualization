"""
Q9. Student Information System
Create variables to store a student's:
Name
Age
CGPA
Placement status
Display all the information along with the data type of each variable.

Topics: Variables, int, float, string, Boolean, type().
"""

# Student details stored in variables of different data types
name = "Ananya Sharma"        # string
age = 21                      # int
cgpa = 8.75                   # float
is_placed = True              # boolean

# Display the information along with the data type of each variable
print("Name: ", name, " -> Data Type:", type(name))
print("Age: ", age, " -> Data Type:", type(age))
print("CGPA: ", cgpa, " -> Data Type:", type(cgpa))
print("Placement Status: ", is_placed, " -> Data Type:", type(is_placed))
